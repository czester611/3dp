// Stały keystore dla WSZYSTKICH wersji (wymóg OTA: aktualizacja musi mieć ten sam podpis).
// Plik keystore.properties (poza repo!): storeFile, storePassword, keyAlias, keyPassword.
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

android {
    namespace = "pl.u1companion"
    compileSdk = 36

    defaultConfig {
        applicationId = "pl.u1companion"
        minSdk = 29
        targetSdk = 36
        versionCode = 1
        versionName = "0.1.0"
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"

        // OTA - repozytorium z GitHub Releases (konfigurowalne w gradle.properties / -P).
        val owner = (project.findProperty("updateRepoOwner") as String?) ?: "CHANGE_ME"
        val repo = (project.findProperty("updateRepoName") as String?) ?: "u1-companion"
        buildConfigField("String", "UPDATE_REPO_OWNER", "\"$owner\"")
        buildConfigField("String", "UPDATE_REPO_NAME", "\"$repo\"")
    }

    signingConfigs {
        if (keystoreProps.getProperty("storeFile") != null) {
            create("release") {
                storeFile = rootProject.file(keystoreProps.getProperty("storeFile"))
                storePassword = keystoreProps.getProperty("storePassword")
                keyAlias = keystoreProps.getProperty("keyAlias")
                keyPassword = keystoreProps.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            signingConfig = signingConfigs.findByName("release")
            isMinifyEnabled = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }
}

