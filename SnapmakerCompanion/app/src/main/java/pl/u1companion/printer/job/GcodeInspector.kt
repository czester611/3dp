package pl.u1companion.printer.job

import kotlinx.serialization.Serializable
import java.io.File
import java.io.RandomAccessFile

/** Metadane wyciągnięte z komentarzy G-code (OrcaSlicer / Snapmaker Orca / PrusaSlicer / Cura). */
@Serializable
data class GcodeMeta(
    val slicer: String? = null,
    val printerModel: String? = null,
    val filamentTypes: List<String> = emptyList(),
    val nozzleTemps: List<Int> = emptyList(),
    val bedTemp: Int? = null,
    val layerHeight: Float? = null,
    val infill: String? = null,
    val estimatedTime: String? = null,
    val usedTools: Set<Int> = emptySet(),
    val maxZ: Float? = null,
    val isKlipperFlavor: Boolean? = null,
) {
    /** Czy plik wygląda na pocięty dla Snapmaker U1 (profil Orca "Snapmaker U1 ..."). */
    val looksLikeU1: Boolean get() = printerModel?.contains("U1", ignoreCase = true) == true

    /** Czy plik wygląda na przeznaczony dla innej drukarki - ostrzeżenie przed drukiem. */
    val looksForeign: Boolean get() = printerModel != null && !looksLikeU1
}

/**
 * Czyta początek i koniec pliku (Orca zapisuje CONFIG_BLOCK na końcu) - nie parsuje całego G-code.
 * Klucze wg konwencji OrcaSlicer (np. "; filament_type = PLA;PETG"); dla innych slicerów best-effort.
 */
object GcodeInspector {
    private const val HEAD = 256 * 1024
    private const val TAIL = 512 * 1024
    private val kv = Regex("^;\\s*([A-Za-z0-9_ ]+?)\\s*[=:]\\s*(.*)$")
    private val toolChange = Regex("^T(\\d+)\\b")

    fun inspect(file: File): GcodeMeta {
        val text = readHeadTail(file)
        val map = HashMap<String, String>()
        val tools = sortedSetOf<Int>()
        var slicer: String? = null
        text.lineSequence().forEach { raw ->
            val line = raw.trim()
            if (slicer == null && line.startsWith("; generated by", ignoreCase = true)) slicer = line.removePrefix(";").trim()
            kv.find(line)?.let { m -> map.putIfAbsent(m.groupValues[1].trim().lowercase(), m.groupValues[2].trim()) }
            toolChange.find(line)?.let { tools += it.groupValues[1].toInt() }
        }
        fun list(k: String) = map[k]?.split(';', ',')?.map { it.trim() }?.filter { it.isNotEmpty() }.orEmpty()
        return GcodeMeta(
            slicer = slicer,
            printerModel = map["printer_model"] ?: map["printer_settings_id"],
            filamentTypes = list("filament_type"),
            nozzleTemps = (list("nozzle_temperature").ifEmpty { list("temperature") }).mapNotNull { it.toIntOrNull() },
            bedTemp = (map["hot_plate_temp"] ?: map["bed_temperature"])?.split(';', ',')?.firstOrNull()?.trim()?.toIntOrNull(),
            layerHeight = map["layer_height"]?.toFloatOrNull(),
            infill = map["sparse_infill_density"] ?: map["fill_density"],
            estimatedTime = map["estimated printing time (normal mode)"] ?: map["model printing time"],
            usedTools = tools,
            maxZ = map["max_z_height"]?.toFloatOrNull(),
            isKlipperFlavor = map["gcode_flavor"]?.equals("klipper", ignoreCase = true),
        )
    }

    private fun readHeadTail(file: File): String = RandomAccessFile(file, "r").use { raf ->
        val len = raf.length()
        if (len <= HEAD + TAIL) {
            val buf = ByteArray(len.toInt()); raf.readFully(buf); return String(buf, Charsets.UTF_8)
        }
        val head = ByteArray(HEAD).also { raf.readFully(it) }
        raf.seek(len - TAIL)
        val tail = ByteArray(TAIL).also { raf.readFully(it) }
        String(head, Charsets.UTF_8) + "\n" + String(tail, Charsets.UTF_8)
    }
}
